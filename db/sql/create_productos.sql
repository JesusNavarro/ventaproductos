create table productos (
	productoId INTEGER PRIMARY KEY AUTOINCREMENT,
	codigoBarras varchar(25) not null UNIQUE,	-- aumentar a 25
	codigoNumerico integer null,
	claves varchar(255) null,
	proveedorId integer not null,
	descripcion varchar(255) not null,
	preferenciaVenta integer null,
	seCompraPor varchar(15) not null,
	numeroUnidades integer null,
	numeroKgs DECIMAL(6,2) null,
	unidadInv varchar(15) not null,
	costoSinIvaUnidad DECIMAL(8,3) null,
	precioUnidad DECIMAL(8,3) null,
	costoSinIvaPaquete DECIMAL(10,3) null,
	precioPaquete DECIMAL(10,3) null,
	costoSinIvaKg DECIMAL(10,3) null,
	precioKg DECIMAL(10,3) null,
	muestraUnidad boolean,
	muestraPaquete boolean,
	muestraKg boolean,
	existenciaUnidades DECIMAL(10,3) null,
	existenciaPaquetes DECIMAL(8,3) null,
	existenciaKgs DECIMAL(10,3) null,
	minimoUnidades  DECIMAL(8,3) null,
	minimoPaquetes DECIMAL(8,3) null,
	minimoKgs DECIMAL(8,3) null,
	ultimaVenta DATETIME null,
	activo boolean,
	created_date DATETIME not null,
	modified_date DATETIME not null
);